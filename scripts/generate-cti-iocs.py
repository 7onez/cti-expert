def role_of(s):
    r = str(s.get("role", "")).lower()
    if r in ("actor", "victim", "infrastructure", "associate", "witness"):
        return r
    if str(s.get("type", "")).lower() in INFRA_TYPES:
        return "infrastructure"
    return "unknown"

# --- §2.5 exclusion gate -------------------------------------------------
# Subjects/findings marked rejected/masked (a §2.5 name-collision innocent, a
# registrar privacy-proxy value, a false-positive attribution) must NEVER be
# harvested as IOCs — even when the value is mentioned inside an otherwise
# legitimate subject's `notes` or a finding's `description`. Two knobs:
#   * per-item: subject/finding role in EXCLUDED_ROLES, an excluding tag/type,
#     or an explicit `"excluded": true` / `"ioc_exclude": true` flag.
#   * report-level: `data["ioc_exclude"]` = [values] dropped anywhere they are
#     harvested from. Backward-compatible: absent markers → identical output.
EXCLUDED_ROLES = {"rejected", "masked", "excluded", "uninvolved", "innocent",
                  "false-positive", "false_positive", "fp"}
EXCLUDED_FINDING_TYPES = {"false-positive", "false_positive", "rejected", "excluded"}
EXCLUDED_TAGS = {"rejected", "masked", "excluded", "uninvolved",
                 "false-positive", "false_positive", "name-collision", "§2.5"}


def _is_excluded_subject(s):
    if s.get("excluded") is True or s.get("ioc_exclude") is True:
        return True
    return str(s.get("role", "")).lower() in EXCLUDED_ROLES


def _is_excluded_finding(f):
    if f.get("excluded") is True or f.get("ioc_exclude") is True:
        return True
    if str(f.get("type", "")).lower() in EXCLUDED_FINDING_TYPES:
        return True
    return bool({str(t).lower() for t in (f.get("tags") or [])} & EXCLUDED_TAGS)


def _exclude_values(data):
    return {str(v).strip().lower() for v in (data.get("ioc_exclude") or []) if str(v).strip()}


def _complete_ip(typ, value):
    """An IP indicator must be a complete address of the family its type claims.

    A truncated fragment (a bare hextet run, a prefix cut out of a longer address) matches the
    loose IPv6 scan and must never leave as an IOC — it names nothing and collides with
    unrelated addresses. ``ip`` accepts either family; ``ipv4``/``ipv6`` must match theirs.
    """
    try:
        addr = ipaddress.ip_address(str(value).strip())
    except ValueError:
        return False
    want = str(typ).lower()
    if want == "ipv4":
        return addr.version == 4
    if want == "ipv6":
        return addr.version == 6
    return want == "ip"


def detect_social(u):
    for rx, plat in SOCIAL:
        m = rx.search(u)
        if m and m.group(1) and len(m.group(1)) > 1 and m.group(1).lower() not in (
                "p", "status", "share", "intent", "home", "about"):
            return {"platform": plat, "handle": m.group(1), "url": u}
    return None


def detect_msg(u):
    for rx, plat in MSG:
        m = rx.search(u)
        if m and m.group(1):
            return {"platform": plat, "handle": m.group(1), "url": u}
    return None


def host_of(u):
    m = re.match(r"^(?:https?://)?([^/?#\s]+)", u or "", re.I)
    if not m:
        return ""
    h = m.group(1).split("@")[-1].lower()
    return h[4:] if h.startswith("www.") else h


def extract(data):
    subjects = data.get("subjects", []) or []
    findings = data.get("findings", []) or []
    conns = data.get("connections", []) or []
    sources = data.get("sources", []) or []
    out, seen = [], {}
    exclude = _exclude_values(data)

    def add(cat, typ, value, role="unknown", conf=0, platform=None, source=None, sid=None):
        if value is None:
            return
        value = str(value).strip()
        if not value:
            return
        if str(typ).lower() in ("ip", "ipv4", "ipv6"):
            if not _complete_ip("ip", value):
                return                      # fragment or prefix — names nothing, never an IOC
            typ = "ipv4" if ipaddress.ip_address(value.strip()).version == 4 else "ipv6"
        if value.lower() in exclude:  # §2.5: dropped no matter where it was harvested
            return
        key = "%s|%s|%s" % (cat, typ, value.lower())
        if key in seen:
            ex = seen[key]
            if int(conf or 0) > int(ex.get("confidence") or 0):
                ex["confidence"] = conf
            if ex.get("role") == "unknown" and role != "unknown":
                ex["role"] = role
            if not ex.get("source") and source:
                ex["source"] = source
            return
        rec = {"category": cat, "type": typ, "value": value, "role": role,
               "confidence": conf, "platform": platform, "source": source, "subject_id": sid}
        seen[key] = rec
        out.append(rec)

    def scan(text, role, conf, source=None, sid=None):
        if not text:
            return
        text = str(text)
        for u in RX["url"].findall(text):
            u = u.rstrip(".,);]")
            so = detect_social(u)
            if so:
                add("social", so["platform"], so["handle"], role, conf, so["platform"], u, sid)
                continue
            mo = detect_msg(u)
            if mo:
                add("messaging", mo["platform"], mo["handle"], role, conf, mo["platform"], u, sid)
                continue
            if is_reference_host(host_of(u)):  # research/registry/source host, not a target IOC
                continue
            add("network", "url", u, role, conf, None, source, sid)
        for v in RX["email"].findall(text):
            if is_reference_host(v.rsplit("@", 1)[-1]):   # a registry / service contact mailbox
                continue
            add("contact", "email", v.lower(), role, conf, None, source, sid)
        for v in RX["ipv4"].findall(text):
            add("network", "ipv4", v, role, conf, None, source, sid)
        for v in RX["ipv6"].findall(text):
            if ":" in v and not re.fullmatch(r"[0-9a-fA-F]{4,}", v):
                add("network", "ipv6", v, role, conf, None, source, sid)
        for v in RX["sha256"].findall(text):
            add("network", "sha256", v.lower(), role, conf, None, source, sid)
        for v in RX["sha1"].findall(text):
            add("network", "sha1", v.lower(), role, conf, None, source, sid)
        for v in RX["md5"].findall(text):
            add("network", "md5", v.lower(), role, conf, None, source, sid)
        for v in RX["eth"].findall(text):
            add("financial", "eth-wallet", v, role, conf, None, source, sid)
        for v in RX["btc"].findall(text):
            add("financial", "btc-wallet", v, role, conf, None, source, sid)
        for v in RX["iban"].findall(text):
            ok = iban_ok(v)          # only checksum-valid accounts become indicators
            if ok:
                add("financial", "iban", ok, role, conf, None, source, sid)
        dl = RX["email"].sub(" ", RX["url"].sub(" ", text))
        for v in RX["domain"].findall(dl):
            v = v.lower().rstrip(".")
            if "." not in v or is_reference_host(v):
                continue
            if v.rsplit(".", 1)[-1] in NOT_TLDS:       # "next.js", "styles.css" — a file, not a host
                continue
            if any(v in x for x in exclude):           # "godaddy.com" inside "GoDaddy.com, LLC"
                continue
            add("network", "domain", v, role, conf, None, source, sid)

    # 1) subjects
    for s in subjects:
        if _is_excluded_subject(s):     # §2.5: rejected/masked subject → no IOCs, no notes scan
            continue
        role, conf, t = role_of(s), int(s.get("confidence") or 0), str(s.get("type", "")).lower()
        if t in SUBJECT_MAP:
            cat, typ = SUBJECT_MAP[t]
            add(cat, typ, s.get("label"), role, conf, None, None, s.get("id"))
        pcat, ptyp = SUBJECT_MAP.get(t, (None, None))
        for a in (s.get("aliases") or []):
            if pcat in ("network", "contact", "financial"):
                add(pcat, ptyp, a, role, max(conf - 10, 0), None, None, s.get("id"))
            else:
                add("identity", "alias", a, role, max(conf - 10, 0), None, None, s.get("id"))
        for sel in (s.get("selectors") or []):
            if not sel or not sel.get("value"):
                continue
            u = sel.get("url") or sel.get("value")
            so = detect_social(str(u))
            if so:
                add("social", so["platform"], so["handle"], role, conf, so["platform"], so["url"], s.get("id"))
                continue
            mo = detect_msg(str(u))
            if mo:
                add("messaging", mo["platform"], mo["handle"], role, conf, mo["platform"], mo["url"], s.get("id"))
                continue
            cat = {"email": "contact", "phone": "contact", "username": "identity",
                   "wallet": "financial", "iban": "financial", "bank_account": "financial",
                   "bic": "financial", "swift": "financial",
                   }.get(str(sel.get("type", "")).lower(), "identity")
            add(cat, sel.get("type", "selector"), sel.get("value"), role, conf,
                sel.get("platform"), sel.get("url"), s.get("id"))
        scan(s.get("notes"), role, conf, None, s.get("id"))

    # 2) explicit indicators
    for o in (data.get("indicators") or []):
        if o and o.get("value"):
            add(o.get("category", "network"), o.get("type", "indicator"), o.get("value"),
                o.get("role", "unknown"), int(o.get("confidence") or 0), None,
                o.get("source_url"), o.get("subject_id"))

    # 3) findings
    by_id = {s.get("id"): s for s in subjects}
    for f in findings:
        if _is_excluded_finding(f):     # §2.5: false-positive/rejected finding → don't harvest its prose
            continue
        sub = by_id.get(f.get("subject_id"))
        role = role_of(sub) if sub else "unknown"
        conf = int(f.get("confidence") or 0)
        # source_url is PROVENANCE (the registry / platform the claim cites), never an indicator.
        # `ioc_scan: false` = an analyst-graded finding whose indicators are already tagged
        # explicitly (its subjects); its prose cites references and is not harvested.
        if f.get("ioc_scan") is False:
            continue
        text = "%s %s" % (f.get("description", ""), " ".join(f.get("tags", []) or []))
        scan(text, role, conf, f.get("source_url"), f.get("subject_id"))

    # 4) source URLs — provenance only, unless the row is explicitly tagged as an indicator
    for s in sources:
        if s.get("url") and (s.get("indicator") is True or "indicator" in (s.get("tags") or [])):
            scan(s["url"], "unknown", 55, s["url"], None)

    return out


def attribution(data):
    """Actor↔subject links for the export. A link whose endpoint is an EXCLUDED subject (rejected,
    masked, an expansion leaf marked `ioc_exclude`) is dropped: naming a stranger's domain next to
    the operator — even as `related_to … possible` — is exactly what a scraper strips the caveat from."""
    exclude = _exclude_values(data)
    by_id = {s.get("id"): s for s in (data.get("subjects") or [])}
    rows = []
    for c in (data.get("connections") or []):
        a, b = by_id.get(c.get("from_id")), by_id.get(c.get("to_id"))
        if (a and _is_excluded_subject(a)) or (b and _is_excluded_subject(b)):
            continue
        # A report-level exclusion applies even when the subject object itself was not flagged:
        # a shared or historical IP kept as a subject must not leave as an operator link.
        ends = {(a.get("label") if a else ""), (b.get("label") if b else "")}
        if any(str(e).strip().lower() in exclude for e in ends if e):
            continue
        rel = str(c.get("relationship") or c.get("type") or "linked_to")
        rows.append({
            "from": a.get("label") if a else c.get("from_id"),
            "to": b.get("label") if b else c.get("to_id"),
            "rel": rel, "strength": c.get("strength", ""),
            "reach": rel.lower() in REACH_RELS,
        })
    return rows


# ----------------------------- writers -----------------------------
def write_flat(inds, attr, case, path):
    lines = ["# " + CREDIT,
             "# CTI Expert indicator/selector export",
             "# Case: %s   Generated: %s" % (case.get("id") or case.get("label") or "?",
                                             datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")),
             "# Fields: type:value  (role / confidence in CSV/STIX export)", ""]
    for cat in ["network", "contact", "identity", "social", "messaging", "financial", "geo"]:
        rows = [i for i in inds if i["category"] == cat]
        if not rows:
            continue
        lines.append("# --- %s (%d) ---" % (cat.upper(), len(rows)))
        for i in rows:
            lines.append("%s:%s" % (i["type"], i["value"]))
        lines.append("")
    if attr:
        lines.append("# --- ATTRIBUTION / RELATIONSHIPS (%d) ---" % len(attr))
        for a in attr:
            lines.append("rel:%s|%s%s|%s" % (a["from"], a["rel"], " [reach]" if a["reach"] else "", a["to"]))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def write_csv(inds, path):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write("# " + CREDIT + "\n")
        w = csv.writer(f)
        w.writerow(["category", "type", "value", "role", "confidence", "platform", "source", "subject_id"])
        for i in inds:
            w.writerow([i["category"], i["type"], i["value"], i["role"], i["confidence"],
                        i.get("platform") or "", i.get("source") or "", i.get("subject_id") or ""])


def write_jsonl(inds, attr, path):
    """One JSON object per line — the streamable IOC list (jq-friendly, diff-friendly,
    ingestable by SIEM/pipelines). Indicators first, then attribution links tagged
    with kind:'attribution' so a single file carries the whole set."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for i in inds:
            rec = {"kind": "indicator", "category": i["category"], "type": i["type"],
                   "value": i["value"], "role": i["role"], "confidence": i["confidence"],
                   "platform": i.get("platform") or "", "source": i.get("source") or "",
                   "subject_id": i.get("subject_id") or ""}
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
        for a in attr:
            f.write(json.dumps({"kind": "attribution", "from": a["from"], "rel": a["rel"],
                                "to": a["to"], "reach": a["reach"]}, ensure_ascii=False) + "\n")

def _now():
    """STIX timestamp: RFC 3339, UTC with a `Z`, millisecond precision (STIX 2.1 §2.16, §3.2)."""
    d = datetime.now(timezone.utc)
    return d.strftime("%Y-%m-%dT%H:%M:%S.") + "%03dZ" % (d.microsecond // 1000)


# STIX 2.1 §2.9: SCO ids are UUIDv5 in this namespace over the RFC 8785 canonical JSON of the
# object's "ID Contributing Properties", so two producers emit the same id for the same value.
STIX_SCO_NAMESPACE = uuid.UUID("00abedb4-aa42-466c-9c01-fed23315a9b7")

# TLP 2.0 marking-definition objects, verbatim from the OASIS CTI TC's published extension
# (oasis-open/cti-stix-common-objects, extension-definition-specifications/tlp-2.0). These are
# fixed, shared objects: their ids MUST NOT be minted locally. STIX 2.1 §7.2.1.4 only defines the
# TLP 1.0 set (white/green/amber/red), which has no AMBER+STRICT and no CLEAR.
TLP2_EXTENSION = "extension-definition--60a3c5c5-0d10-413e-aab3-9e08dde9e88d"
TLP2_MARKING_IDS = {
    "clear": "marking-definition--94868c89-83c2-464b-929b-a1a8aa3c8487",
    "green": "marking-definition--bab4a63c-aed9-4cf5-a766-dfca5abac2bb",
    "amber": "marking-definition--55d920b0-5e8b-4f79-9ee9-91f868d9b421",
    "amber+strict": "marking-definition--939a9414-2ddd-4d32-a0cd-375ea402b003",
    "red": "marking-definition--e828b379-4e03-4974-9ac4-e53a884c97c1",
}
DEFAULT_TLP = "amber"   # the skill's default handling marking for a case that records none


def _tlp_fields(data):
    """All legacy markings and source-preserving metadata from REPORT.json."""
    case = data.get("case") if isinstance(data.get("case"), dict) else {}
    fields = []
    for prefix, obj in (("case.", case), ("", data)):
        fields.extend([(prefix + "classification", obj.get("classification"), False),
                       (prefix + "tlp", obj.get("tlp"), True)])
        for key, value_key in (("tlp_sources", "tlp"), ("tlp_unreadable", "value")):
            entries = obj.get(key) or []
            if not isinstance(entries, list):
                fields.append((prefix + key, entries, True))
                continue
            for entry in entries:
                value = entry.get(value_key) if isinstance(entry, dict) else entry
                label = entry.get("source") if isinstance(entry, dict) else key
                fields.append((prefix + str(label), value, True))
    return fields


def tlp_level(data):
    """(level, problem) for the report's own marking, never raises. The most restrictive TLP 2.0
    level among case.classification, case.tlp, classification and tlp (cti_case_meta.tlp_resolve);
    DEFAULT_TLP when none is recorded; (None, problem) when one is present but unreadable."""
    level, problem = tlp_resolve(_tlp_fields(data))
    if problem:
        return None, problem
    return level or DEFAULT_TLP, None


def recorded_tlp(data):
    """The strictest READABLE marking the report records (lower-case), or None, never raises.
    Unreadable values beside it never hide it; DEFAULT_TLP is not a recorded marking."""
    readable, _, _ = tlp_collect(_tlp_fields(data))
    return tlp_most_restrictive([lv for _, lv in readable])


def stix_tlp(data, override=None, allow_red=False, allow_downgrade=False):
    """(level, error) for the STIX export, failing closed: an explicit `override` (--tlp) replaces
    the report's marking; otherwise an unreadable marking is an error, never a default. TLP:RED is
    an error unless `allow_red` (--allow-red): RED is for named recipients only. An override LESS
    restrictive than the strictest readable case marking is an error unless `allow_downgrade`
    (--allow-downgrade); a RED case needs both flags to be exported under a lower level."""
    if override is not None:
        level = tlp_parse(override)
        if not level:
            return None, "--tlp %r is not a TLP level (clear, green, amber, amber+strict, red)" % override
    else:
        level, problem = tlp_level(data)
        if problem:
            return None, ("%s; refusing to guess the STIX marking. Fix the case marking or pass "
                          "--tlp LEVEL explicitly." % problem)
    recorded = recorded_tlp(data)
    if (level == "red" or recorded == "red") and not allow_red:
        return None, ("the case or export is TLP:RED (named recipients only); pass --allow-red "
                      "to authorise STIX export.")
    if recorded and TLP_ORDER.index(level) < TLP_ORDER.index(recorded) and not allow_downgrade:
        return None, ("--tlp %s is LESS restrictive than the case marking TLP:%s; pass "
                      "--allow-downgrade to authorise the downgrade."
                      % (level.upper(), recorded.upper()))
    return level, None


def tlp_marking(level):
    return {"type": "marking-definition", "spec_version": "2.1", "id": TLP2_MARKING_IDS[level],
            "created": "2022-10-01T00:00:00.000Z", "name": "TLP:" + level.upper(),
            "extensions": {TLP2_EXTENSION: {"extension_type": "property-extension", "tlp_2_0": level}}}


def sco_id(sco_type, contributing):
    """Deterministic SCO id (STIX 2.1 §2.9 / §3.4): UUIDv5 over RFC 8785 canonical JSON.
    For these flat string-valued property sets, sorted keys + no whitespace + raw UTF-8 IS the
    RFC 8785 form."""
    name = json.dumps(contributing, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return "%s--%s" % (sco_type, uuid.uuid5(STIX_SCO_NAMESPACE, name))


def _stix_literal(s):
    """A STIX pattern string constant: only `'` and `\\` are escaped (STIX 2.1 §9)."""
    return "'%s'" % str(s).replace("\\", "\\\\").replace("'", "\\'")


def _vocab(s, fallback):
    """Lowercase a-z0-9 and hyphen only — the form STIX requires of relationship_type and
    open-vocabulary literals (§3.1, §5.1)."""
    v = re.sub(r"[^a-z0-9]+", "-", str(s or "").lower()).strip("-")
    return v if len(v) >= 3 else fallback


# platform labels the extractor uses -> account-type-ov values where the vocabulary has one
_ACCOUNT_TYPE = {"x/twitter": "twitter", "twitter": "twitter", "facebook": "facebook", "skype": "skype"}


def build_stix(inds, attr, data, now=None, tlp=None, allow_red=False, allow_downgrade=False):
    """The STIX 2.1 bundle as a dict. See techniques/ioc-export.md for what it guarantees.
    The marking comes from stix_tlp(data, tlp, allow_red, allow_downgrade); its refusal raises
    ValueError, so no caller can obtain a bundle under a guessed, unauthorised RED or unauthorised
    downgraded marking."""
    case = data.get("case", {})
    now = now or _now()
    level, err = stix_tlp(data, tlp, allow_red, allow_downgrade)
    if err:
        raise ValueError(err)
    marking = tlp_marking(level)
    marks = [marking["id"]]
    producer = "identity--" + str(uuid.uuid4())
    objs = [marking, {
        "type": "identity", "spec_version": "2.1", "id": producer,
        "created": now, "modified": now,
        "name": "CTI Expert case %s" % (case.get("id") or case.get("label") or "?"),
        "identity_class": "system",
        "description": CREDIT,
        "object_marking_refs": marks,
    }]
    seen_ids = {marking["id"], producer}
    STIX_SCO = {
        "ipv4": "ipv4-addr", "ipv6": "ipv6-addr", "domain": "domain-name",
        "url": "url", "email": "email-addr",
    }
    HASH_KEYS = {"md5": "MD5", "sha1": "SHA-1", "sha256": "SHA-256"}

    def pattern_for(i):
        t = i["type"]
        if t in STIX_SCO:
            return "[%s:value = %s]" % (STIX_SCO[t], _stix_literal(i["value"]))
        if t in HASH_KEYS:
            return "[file:hashes.'%s' = %s]" % (HASH_KEYS[t], _stix_literal(i["value"]))
        return None

    def emit(obj):
        if obj["id"] not in seen_ids:     # deterministic SCO ids collapse a repeated value
            seen_ids.add(obj["id"])
            objs.append(obj)
        return obj["id"]

    sub_stix = {}  # subject_id -> stix id (for relationships)

    for i in inds:
        t, val = i["type"], i["value"]
        if t in STIX_SCO:
            props = {"value": val}
            oid = emit(dict(type=STIX_SCO[t], spec_version="2.1", id=sco_id(STIX_SCO[t], props),
                            object_marking_refs=marks, **props))
        elif t in HASH_KEYS:
            props = {"hashes": {HASH_KEYS[t]: val}}
            oid = emit(dict(type="file", spec_version="2.1", id=sco_id("file", props),
                            object_marking_refs=marks, **props))
        elif i["category"] in ("social", "messaging") or t == "username":
            plat = str(i.get("platform") or "").lower()
            props = {"account_login": val, "account_type": _ACCOUNT_TYPE.get(plat) or _vocab(plat, "osint")}
            oid = emit(dict(type="user-account", spec_version="2.1", id=sco_id("user-account", props),
                            object_marking_refs=marks, **props))
        elif t in ("name", "org-name"):
            oid = emit({"type": "identity", "spec_version": "2.1", "id": "identity--%s" % uuid.uuid4(),
                        "created": now, "modified": now, "created_by_ref": producer, "name": val,
                        "identity_class": "individual" if t == "name" else "organization",
                        "object_marking_refs": marks})
        else:
            # phone, wallet, alias, location, device... -> custom object (STIX 2.1 §11.2)
            oid = emit({"type": "x-cti-selector", "spec_version": "2.1",
                        "id": "x-cti-selector--%s" % uuid.uuid4(),
                        "created": now, "modified": now, "created_by_ref": producer,
                        "selector_type": t, "category": i["category"], "value": val,
                        "role": i["role"], "object_marking_refs": marks})
        if i.get("subject_id") and i["subject_id"] not in sub_stix:
            sub_stix[i["subject_id"]] = oid
        pat = pattern_for(i)
        if pat:
            ind = {
                "type": "indicator", "spec_version": "2.1", "id": "indicator--%s" % uuid.uuid4(),
                "created": now, "modified": now, "created_by_ref": producer,
                "name": "%s %s" % (t, val), "pattern": pat, "pattern_type": "stix",
                "pattern_version": "2.1", "valid_from": now,
                "labels": [i["category"], i["role"]], "object_marking_refs": marks,
            }
            conf = int(i.get("confidence") or 0)
            if conf > 0:    # absent = unspecified (§3.2); 0 would assert "no confidence"
                ind["confidence"] = min(conf, 100)
            objs.append(ind)

    for a in attr:
        fid = sub_stix.get(_find_sid(data, a["from"]))
        tid = sub_stix.get(_find_sid(data, a["to"]))
        if fid and tid:
            objs.append({
                "type": "relationship", "spec_version": "2.1", "id": "relationship--%s" % uuid.uuid4(),
                "created": now, "modified": now, "created_by_ref": producer,
                "relationship_type": _vocab(a["rel"], "related-to"),
                "source_ref": fid, "target_ref": tid,
                "description": ("can reach / contacted" if a["reach"] else a["rel"]),
                "object_marking_refs": marks,
            })

    return {"type": "bundle", "id": "bundle--%s" % uuid.uuid4(),
            "x_cti_generator": "CTI Expert", "x_cti_generator_url": CREDIT_URL,
            "objects": objs}


def write_stix(inds, attr, data, path, tlp=None, allow_red=False, allow_downgrade=False):
    bundle = build_stix(inds, attr, data, tlp=tlp, allow_red=allow_red,
                        allow_downgrade=allow_downgrade)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(bundle, f, indent=2, ensure_ascii=False)


def _find_sid(data, label):
    for s in (data.get("subjects") or []):
        if s.get("label") == label:
            return s.get("id")
    return None


def main(argv):
    fmt = "all"
    tlp = None
    allow_red = allow_downgrade = False
    args = []
    i = 0
    while i < len(argv):
        if argv[i] == "--format" and i + 1 < len(argv):
            fmt = argv[i + 1].lower()
            i += 2
        elif argv[i] == "--tlp" and i + 1 < len(argv):
            tlp = argv[i + 1]
            i += 2
        elif argv[i] == "--allow-red":
            allow_red = True
            i += 1
        elif argv[i] == "--allow-downgrade":
            allow_downgrade = True
            i += 1
        else:
            args.append(argv[i])
            i += 1
    if len(args) < 2:
        print("usage: generate-cti-iocs.py <case.json> <out_prefix> [--format stix|flat|csv|jsonl|all]"
              " [--tlp LEVEL] [--allow-red] [--allow-downgrade]")
        return 2
    case_path, out = args[0], args[1]
    try:
        with open(case_path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        print("error: cannot read/parse case JSON %r: %s" % (case_path, e))
        return 1

    level = None
    if fmt in ("all", "stix"):
        # decided before anything is written: a refused marking leaves no partial export behind
        level, err = stix_tlp(data, tlp, allow_red, allow_downgrade)
        if err:
            print("error: STIX TLP marking: " + err, file=sys.stderr)
            return 2
        recorded = recorded_tlp(data)
        if tlp is not None and recorded and TLP_ORDER.index(level) < TLP_ORDER.index(recorded):
            print("warning: --tlp %s is LESS restrictive than the case marking TLP:%s"
                  % (level.upper(), recorded.upper()), file=sys.stderr)

    inds = extract(data)
    attr = attribution(data)
    case = data.get("case", {})

    out_dir = os.path.dirname(os.path.abspath(out))
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir, exist_ok=True)

    written = []
    if fmt in ("all", "flat"):
        p = (out + ".txt") if fmt == "all" else out
        write_flat(inds, attr, case, p)
        written.append(p)
    if fmt in ("all", "csv"):
        p = (out + ".csv") if fmt == "all" else out
        write_csv(inds, p)
        written.append(p)
    if fmt in ("all", "stix"):
        p = (out + ".stix.json") if fmt == "all" else out
        write_stix(inds, attr, data, p, tlp=level, allow_red=allow_red,
                   allow_downgrade=allow_downgrade)
        written.append(p)
    if fmt in ("all", "jsonl"):
        p = (out + ".jsonl") if fmt == "all" else out
        write_jsonl(inds, attr, p)
        written.append(p)

    by_cat = {}
    for x in inds:
        by_cat[x["category"]] = by_cat.get(x["category"], 0) + 1
    print("Extracted %d indicators/selectors + %d attribution links" % (len(inds), len(attr)))
    print("  by category: " + ", ".join("%s=%d" % (k, v) for k, v in sorted(by_cat.items())))
    for p in written:
        print("  wrote: %s" % p)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
