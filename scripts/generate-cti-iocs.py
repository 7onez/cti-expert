"""
generate-cti-iocs.py — CTI Expert comprehensive indicator / selector exporter.

Extracts EVERY indicator that can profile or reach an actor or a victim, not just
classic network IOCs:
  * Network IOCs ...... IPv4/IPv6, domains, URLs, file hashes (MD5/SHA1/SHA256)
  * Contact selectors . emails, phone numbers (how a threat actor reaches a victim)
  * Identity selectors  real names, usernames, aliases (profile the actor / victim)
  * Social / web ...... LinkedIn, X, Facebook, Instagram, GitHub, TikTok, ... profiles
  * Messaging ......... Telegram, WhatsApp, Discord, Signal, Skype handles
  * Financial ......... BTC / ETH wallets, IBANs (mod-97 verified), BIC, bank accounts
  * Attribution ....... who is linked to / can reach whom (case connections)

Sources scanned: subjects (typed + aliases + attached selectors + notes), findings (description +
tags), case connections, plus any explicit top-level `indicators[]`. A finding's `source_url` and
the `sources[]` list are PROVENANCE — cited registries, search platforms and scam-check sites —
and are never scanned; a `sources[]` row is harvested only when tagged `"indicator": true`.
Hosts in references/ioc_reference_hosts.json are never harvested from prose either.

Outputs three machine-readable formats for SIEM / TIP ingest and sharing.

Usage:
    uv run generate-cti-iocs.py <case.json> <out_prefix> [--format stix|flat|csv|jsonl|all]
                                [--tlp LEVEL] [--allow-red] [--allow-downgrade]
    python3 generate-cti-iocs.py <case.json> IOC-CASE-0001 --format all

STIX TLP marking: the most restrictive marking among case.classification, case.tlp, classification
and tlp (bare `red` or `TLP:RED`, `TLP:AMBER + STRICT`; WHITE read as CLEAR). With no marking at all
it is TLP:AMBER. A marking that is present but unreadable stops the run (exit 2) unless --tlp LEVEL
sets the level explicitly. A --tlp LEVEL less restrictive than the strictest readable case marking
needs --allow-downgrade (the warning still prints). A TLP:RED case or export needs --allow-red as
well; nothing is written without the required flags.

With --format all (default) writes <out_prefix>.stix.json, .txt, .csv and .jsonl.
With a single format, <out_prefix> is treated as the exact output path.

Author: Hieu Ngo - chongluadao.vn
"""
