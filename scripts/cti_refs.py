#!/usr/bin/env python3
# cti-expert skill — reference-DATA loader for the scripts/ report layer (stdlib only).
"""cti_refs.py — read scripts/references/*.json tunables with a conservative embedded fallback.

Same contract as the engine's WebPivot/tools/wp_refs.load_ref (RULE 3): a group may be written as
a bare value, `{"values": [...]}` or `{"entries": {...}}` with sibling `_comment` keys; every group
named in `fallback` is guaranteed present; a missing or malformed file falls back WITH a stderr
warning, never silently and never by raising.

  load_ref(name, fallback)      -> {group: value}
  docx_strings(lang)            -> the DOCX furniture table for `lang` (English fills any gap)
  malicious_verdict(case_dir)   -> (bool, basis): does the case's own verdict support a malicious
                                   classification? Default False — never malicious by default.
"""
import copy
import json
import os
import sys
import unicodedata

REF_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "references")


def _group(node, default):
    if isinstance(node, dict):
        if isinstance(node.get("values"), list):
            return list(node["values"])
        if isinstance(node.get("entries"), dict):
            return {k: v for k, v in node["entries"].items() if not k.startswith("_")}
        return {k: v for k, v in node.items() if not k.startswith("_")}
    if isinstance(node, list):
        return list(node)
    return copy.deepcopy(default) if node is None else node


def load_ref(name, fallback):
    """{group: value} for every key in `fallback` (plus extra groups the file defines)."""
    path = os.path.join(REF_DIR, name)
    try:
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        if not isinstance(doc, dict):
            raise ValueError("top level is not a JSON object")
    except Exception as exc:  # noqa: BLE001 — degrade to the fallback, loudly
        sys.stderr.write(f"[refs] WARNING: could not load {path} ({exc}); using the minimal "
                         "embedded fallback — coverage is REDUCED.\n")
        return copy.deepcopy(fallback)
    out = {k: _group(v, None) for k, v in doc.items() if not k.startswith("_")}
    for key, default in fallback.items():
        if out.get(key) is None:
            sys.stderr.write(f"[refs] WARNING: {os.path.basename(path)} lacks group {key!r}; "
                             "using the embedded fallback.\n")
            out[key] = copy.deepcopy(default)
    return out


# ------------------------------------------------------------------ DOCX furniture (i18n)
_DOCX_FALLBACK = {"strings": {"en": {
    "cover_title": "CTI REPORT", "cover_subtitle_default": "Intelligence Summary",
    "report_id": "Report ID", "classification": "Classification", "date": "Date",
    "analyst": "Analyst", "analyst_default": "AI-Assisted OSINT", "subject": "Subject",
    "status": "Status", "header_title": "CTI REPORT", "footer_title": "CTI Report",
    "page": "Page", "credit": "Generated by CTI Expert", "contents": "Table of Contents",
    "visual_analytics": "Visual Analytics",
    "confidence_scale": "Confidence Scale (ICD-203 \u00d7 Admiralty)",
    "campaign_heatmaps": "Campaign Heatmaps", "finding_statistics": "Finding Statistics",
    "event_timeline": "Event Timeline", "entity_relationships": "Entity Relationships",
    "network_topology": "Network Topology", "visitor_intelligence": "Visitor Intelligence",
    "evidence_screenshots": "Evidence Screenshots", "statistical_analysis": "Statistical Analysis",
    "timeline": "Timeline",
}}, "status_values": {}}


def docx_languages():
    return sorted(load_ref("docx_i18n.json", _DOCX_FALLBACK)["strings"])


def docx_strings(lang="en"):
    """The DOCX furniture strings for `lang`, NFC-normalised so Vietnamese diacritics render as
    precomposed glyphs. A key missing from `lang` falls back to English, never to an empty label;
    an unknown language warns and renders English."""
    ref = load_ref("docx_i18n.json", _DOCX_FALLBACK)
    table = ref["strings"]
    base = dict(_DOCX_FALLBACK["strings"]["en"])
    base.update(table.get("en") or {})
    lang = (lang or "en").strip().lower()
    if lang not in table:
        sys.stderr.write(f"[refs] WARNING: no DOCX strings for lang={lang!r}; rendering English.\n")
        lang = "en"
    out = dict(base)
    out.update({k: v for k, v in (table.get(lang) or {}).items() if isinstance(v, str) and v})
    status = (ref.get("status_values") or {}).get(lang) or {}
    out["_status_values"] = {str(k).lower(): v for k, v in status.items()}
    return {k: (unicodedata.normalize("NFC", v) if isinstance(v, str) else v) for k, v in out.items()}


# ------------------------------------------------------------------ malicious-verdict gate
_VERDICT_FALLBACK = {
    # conservative: only an analyst-stated malicious class whose collection SUPPORTED the claim
    "malicious_target_classes": ["confirmed_scam", "suspected_scam", "threat_actor_infra"],
    "supporting_verdicts": ["supported", "partially_supported"],
    "benign_target_classes": ["benign_check"],
    "benign_refuting_verdicts": ["contradicted"],
    "never_malicious_target_classes": ["victim_host"],
}


def _load_json(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:  # noqa: BLE001
        return None


def verdict_of(target_class, premise_verdict):
    """(bool, basis) from a target class + premise verdict, per references/malicious_verdict.json."""
    ref = load_ref("malicious_verdict.json", _VERDICT_FALLBACK)
    tc = str(target_class or "").strip().lower()
    pv = str(premise_verdict or "").strip().lower()
    if not tc and not pv:
        return False, "no case verdict recorded — not classified malicious by default"
    if tc in ref["never_malicious_target_classes"]:
        return False, f"target_class {tc} is never classified malicious"
    if tc in ref["malicious_target_classes"] and pv in ref["supporting_verdicts"]:
        return True, f"target_class {tc}, premise verdict {pv}"
    if tc in ref["benign_target_classes"] and pv in ref["benign_refuting_verdicts"]:
        return True, f"benign premise {pv} by the collection"
    return False, f"target_class {tc or 'unstated'}, premise verdict {pv or 'unstated'} — does not support a malicious classification"


def malicious_verdict(case_dir):
    """(bool, basis) for a case dir: assessment.json premise_verdict + scope.json target_class."""
    if not case_dir or not os.path.isdir(case_dir):
        return False, "no case directory — not classified malicious by default"
    a = _load_json(os.path.join(case_dir, "assessment.json")) or {}
    s = _load_json(os.path.join(case_dir, "scope.json")) or {}
    tc = (s.get("target_class") if isinstance(s, dict) else None) or ""
    pv = (a.get("premise_verdict") if isinstance(a, dict) else None) or ""
    return verdict_of(tc, pv)
